"""Render one app ontology file (CONN-CRAFT-SUITE-API-CONNECTOR-CONTENT-R003).

A pure function from the app source and its tool snapshot to Turtle text. The
file holds the app's ``owl:Ontology`` node, one ``:App`` individual, the
app's domain classes and one ``:UseCase`` individual per functionality. It
imports only the sibling core pack, never the engine ontology.
"""

from __future__ import annotations

from craft_suite_api.content_gen.errors import (
    CONTENT_PARENT_UNKNOWN,
    CONTENT_PROMPT_TOOL_UNKNOWN,
    ContentError,
)
from craft_suite_api.content_gen.sources import (
    ALLOWED_PARENTS,
    AppSource,
    ToolSnapshot,
)

_KG = "http://knuckles.team/kg"
_CORE_IRI = f"{_KG}/artcraft"


def _iri(app: str) -> str:
    return f"{_KG}/artcraft/{app}"


def _tool_ref(app: str, tool: str) -> str:
    """The namespaced tool name content carries for one upstream tool."""
    return f"{app}_{tool}"


def _check_tools(app: str, tools, snapshot: ToolSnapshot) -> None:
    known = snapshot.names()
    for tool in tools:
        if tool not in known:
            raise ContentError(
                CONTENT_PROMPT_TOOL_UNKNOWN,
                f"{app}: tool {tool!r} is not in the snapshot",
            )


def render_ontology(source: AppSource, snapshot: ToolSnapshot) -> str:
    """The Turtle text of ``artcraft-<app>.ttl`` for one app."""
    app = source.app
    lines = [
        "@prefix : <http://knuckles.team/kg#> .",
        f"@prefix app: <{_iri(app)}#> .",
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "",
        f"<{_iri(app)}> a owl:Ontology ;",
        f'    rdfs:label "{app}" ;',
        '    rdfs:comment "Generated by scripts/generate_app_content.py; do not edit." ;',
        f"    owl:imports <{_CORE_IRI}> .",
        "",
        "app:app a :App ;",
        f'    :appNamespace "{app}" ;',
        f'    :appVersion "{snapshot.version}" .',
        "",
    ]
    for cls in source.classes:
        if cls.parent not in ALLOWED_PARENTS:
            raise ContentError(
                CONTENT_PARENT_UNKNOWN,
                f"{app}: class {cls.name!r} names parent {cls.parent!r}",
            )
        lines.append(f"app:{cls.name} a owl:Class ;")
        lines.append(f'    rdfs:label "{cls.name}" ;')
        if cls.description:
            lines.append(f'    rdfs:comment "{cls.description}" ;')
        lines.append(f"    rdfs:subClassOf :{cls.parent} .")
        lines.append("")
    for func in source.functionalities:
        _check_tools(app, func.tools, snapshot)
        lines.append(f"app:use_case_{_slug(func.name)} a :UseCase ;")
        lines.append("    :forApp app:app ;")
        for tool in func.tools:
            lines.append(f'    :usesToolName "{_tool_ref(app, tool)}" ;')
        lines[-1] = lines[-1].rstrip(" ;") + " ."
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _slug(name: str) -> str:
    import re

    return re.sub(r"[^A-Za-z0-9_]+", "_", name).strip("_")
